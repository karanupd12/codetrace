package dev.codetrace.report.sections;

import dev.codetrace.report.ReportData;
import dev.codetrace.report.ReportSection;
import org.springframework.stereotype.Component;

@Component
public class FooterSection implements ReportSection {
    @Override
    public int order() {
        return 1000;
    }

    @Override
    public String id() {
        return "footer";
    }

    @Override
    public String render(ReportData d) {
        return "---\n\n_Generated by CODETRACE, algorithm " + d.report().algorithmVersion()
                + ". Deterministic: the same snapshots and settings always produce the same report._\n";
    }
}
